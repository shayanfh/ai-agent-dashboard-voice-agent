log() { printf '[mozaic-office] %s\n' "$*" | tee -a "$LOG_FILE"; }
die() { log "ERROR: $*"; exit 1; }
on_error() { log "Installation failed at line $1. Inspect $LOG_FILE."; }
trap 'on_error "$LINENO"' ERR

require_root() {
  [[ ${EUID} -eq 0 ]] || die "Run this installer with sudo."
}

check_os() {
  # shellcheck disable=SC1091
  source /etc/os-release
  [[ ${ID:-} == "ubuntu" && ${VERSION_ID:-} == "24.04" ]] || \
    die "This installer supports Ubuntu 24.04 only (detected ${PRETTY_NAME:-unknown})."
  [[ $(dpkg --print-architecture) == "amd64" ]] || \
    die "Only amd64 is currently supported."
}

prompt() {
  local variable=$1 label=$2 default=${3:-} value
  if [[ -n ${!variable:-} ]]; then
    return
  fi
  if [[ -n $default ]]; then
    read -r -p "$label [$default]: " value
    printf -v "$variable" '%s' "${value:-$default}"
  else
    while [[ -z ${value:-} ]]; do
      read -r -p "$label: " value
    done
    printf -v "$variable" '%s' "$value"
  fi
}

prompt_secret() {
  local variable=$1 label=$2 value
  if [[ -n ${!variable:-} ]]; then
    return
  fi
  while [[ -z ${value:-} ]]; do
    read -r -s -p "$label: " value
    printf '\n'
  done
  printf -v "$variable" '%s' "$value"
}

validate_network_values() {
  python3 - "$SERVER_IP" "$NEWROCK_IP" "$LAN_CIDR" "$OFFICE_DID" <<'PY'
import ipaddress
import re
import sys

server, newrock, subnet, did = sys.argv[1:]
network = ipaddress.ip_network(subnet, strict=False)
server_ip = ipaddress.ip_address(server)
newrock_ip = ipaddress.ip_address(newrock)
if server_ip not in network:
    raise SystemExit(f"Server IP {server_ip} is outside {network}")
if newrock_ip not in network:
    raise SystemExit(f"New Rock IP {newrock_ip} is outside {network}")
if server_ip == newrock_ip:
    raise SystemExit("Server and New Rock IP addresses must be different")
if not re.fullmatch(r"\+[1-9]\d{7,14}", did):
    raise SystemExit("Office DID must be E.164, for example +982112345678")
PY
  ip -o -4 addr show | awk '{print $4}' | cut -d/ -f1 | grep -Fxq "$SERVER_IP" || \
    die "SERVER_IP $SERVER_IP is not assigned to this host. Configure its static Netplan address first."
}

random_hex() { openssl rand -hex "$1"; }
random_fernet() { openssl rand -base64 32 | tr '+/' '-_' | tr -d '\n'; }

load_or_collect_configuration() {
  if [[ -r $STATE_FILE ]]; then
    # This file is root-only and contains values generated by this installer.
    # shellcheck disable=SC1090
    source "$STATE_FILE"
  fi

  local detected_ip
  detected_ip=$(ip route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src") {print $(i+1); exit}}')
  detected_ip=${detected_ip:-$(hostname -I | awk '{print $1}')}

  prompt SERVER_IP "Static IPv4 address of this Ubuntu server" "$detected_ip"
  prompt NEWROCK_IP "Static IPv4 address of the New Rock HX440G"
  prompt LAN_CIDR "Office LAN subnet in CIDR notation" "192.168.1.0/24"
  prompt OFFICE_DID "Synthetic E.164 number for the first FXO line" "+982100000000"
  prompt TIMEZONE "Timezone" "Asia/Tehran"
  prompt_secret OPENAI_API_KEY "OpenAI API key"
  prompt_secret ELEVENLABS_API_KEY "ElevenLabs API key"

  POSTGRES_PASSWORD=${POSTGRES_PASSWORD:-$(random_hex 24)}
  MINIO_ACCESS_KEY=${MINIO_ACCESS_KEY:-mozaic$(random_hex 8)}
  MINIO_SECRET_KEY=${MINIO_SECRET_KEY:-$(random_hex 24)}
  APP_SECRET_KEY=${APP_SECRET_KEY:-$(random_hex 32)}
  INTERNAL_API_KEY=${INTERNAL_API_KEY:-$(random_hex 32)}
  WEBSITE_API_KEY=${WEBSITE_API_KEY:-$(random_hex 32)}
  CREDENTIAL_ENCRYPTION_KEY=${CREDENTIAL_ENCRYPTION_KEY:-$(random_fernet)}
  LIVEKIT_API_KEY=${LIVEKIT_API_KEY:-mozaiclocal}
  LIVEKIT_API_SECRET=${LIVEKIT_API_SECRET:-$(random_hex 32)}
  PROVISIONER_API_KEY=${PROVISIONER_API_KEY:-$(random_hex 32)}
  AMI_PASSWORD=${AMI_PASSWORD:-$(random_hex 32)}

  validate_network_values

  printf '\nConfiguration summary:\n'
  printf '  Server:       %s\n' "$SERVER_IP"
  printf '  New Rock:     %s\n' "$NEWROCK_IP"
  printf '  LAN:          %s\n' "$LAN_CIDR"
  printf '  Office DID:   %s\n' "$OFFICE_DID"
  printf '  Frontend:     http://%s:3000\n' "$SERVER_IP"
  printf '  Backend:      http://%s:8000\n' "$SERVER_IP"
  printf '  Asterisk SIP: %s:5060/udp\n' "$SERVER_IP"
  printf '  LiveKit SIP:  %s:5062/udp\n\n' "$SERVER_IP"
  read -r -p "Continue with installation? [y/N]: " answer
  [[ $answer =~ ^[Yy]$ ]] || exit 0
}

