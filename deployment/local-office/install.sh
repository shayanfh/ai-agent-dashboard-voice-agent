}

sync_repo() {
  local url=$1 destination=$2
  if [[ -d $destination/.git ]]; then
    log "Updating $(basename "$destination")"
    git -C "$destination" fetch --prune origin
    git -C "$destination" pull --ff-only
  elif [[ -e $destination ]]; then
    die "$destination exists but is not a Git repository. Move it and rerun."
  else
    log "Cloning $url"
    git clone --depth 1 "$url" "$destination"
  fi
}

fetch_sources() {
  install -d -o root -g root -m 0755 "$INSTALL_ROOT"
  sync_repo "$FRONTEND_REPO" "$INSTALL_ROOT/frontend"
  sync_repo "$BACKEND_REPO" "$INSTALL_ROOT/backend"
  sync_repo "$VOICE_AGENT_REPO" "$INSTALL_ROOT/voice-agent"
  install -d -o root -g root -m 0750 "$RUNTIME_DIR"
  install -o root -g root -m 0644 "$SCRIPT_DIR/docker-compose.yml" "$RUNTIME_DIR/docker-compose.yml"
  install -o root -g root -m 0644 "$SCRIPT_DIR/provision_livekit.py" "$RUNTIME_DIR/provision_livekit.py"
  grep -Fqx 'Dockerfile.local-office' "$INSTALL_ROOT/frontend/.git/info/exclude" || \
    printf 'Dockerfile.local-office\n' >> "$INSTALL_ROOT/frontend/.git/info/exclude"
  install -o root -g root -m 0644 "$SCRIPT_DIR/Dockerfile.frontend" \
    "$INSTALL_ROOT/frontend/Dockerfile.local-office"
}

ensure_include() {
  local file=$1 line=$2
  touch "$file"
  grep -Fqx "$line" "$file" || printf '\n%s\n' "$line" >> "$file"
}

configure_asterisk() {
  log "Configuring native Asterisk"
  local ast_group ast_gid voice_ast
  ast_group=$(id -gn asterisk)
  ast_gid=$(getent group "$ast_group" | cut -d: -f3)
  [[ -n $ast_gid ]] || die "Could not resolve the Asterisk group ID."
  ASTERISK_GID=$ast_gid
  voice_ast="$INSTALL_ROOT/voice-agent/deployment/asterisk"

  install -d -o root -g "$ast_group" -m 2770 /etc/asterisk/ai-agent-generated
  install -d -o asterisk -g "$ast_group" -m 0750 /var/spool/asterisk/monitor/ai-agent
  install -d -o asterisk -g "$ast_group" -m 2770 /var/lib/asterisk/sounds/ai-agent-generated
  install -o root -g "$ast_group" -m 0640 /dev/null /etc/asterisk/ai-agent-generated/pjsip.conf
  install -o root -g "$ast_group" -m 0640 /dev/null /etc/asterisk/ai-agent-generated/extensions.conf

  cp -a /etc/asterisk/pjsip.conf "/etc/asterisk/pjsip.conf.mozaic-backup.$(date +%s)"
  cp -a /etc/asterisk/extensions.conf "/etc/asterisk/extensions.conf.mozaic-backup.$(date +%s)"
  cp -a /etc/asterisk/manager.conf "/etc/asterisk/manager.conf.mozaic-backup.$(date +%s)"

  cat > /etc/asterisk/pjsip_ai_base.conf <<EOF
; Managed by mozaic-office. Local Asterisk transport for New Rock and extensions.
[0.0.0.0-udp]
type=transport
protocol=udp
bind=0.0.0.0:5060
local_net=${LAN_CIDR}
allow_reload=yes
EOF
  ensure_include /etc/asterisk/pjsip.conf '#include pjsip_ai_base.conf'
  ensure_include /etc/asterisk/pjsip.conf '#include ai-agent-generated/pjsip.conf'
  ensure_include /etc/asterisk/extensions.conf '#include ai-agent-generated/extensions.conf'

  cat > /etc/asterisk/rtp_ai.conf <<'EOF'
[general]
rtpstart=10000
rtpend=19999
EOF
  ensure_include /etc/asterisk/rtp.conf '#include rtp_ai.conf'

  install -d -o root -g root -m 0755 /etc/asterisk/manager.d
  cat > /etc/asterisk/manager.d/ai-provisioner.conf <<EOF
[ai-provisioner]
secret=${AMI_PASSWORD}
deny=0.0.0.0/0.0.0.0
permit=127.0.0.1/255.255.255.255
read=system,call,reporting,cdr,dialplan
write=system,command,originate
writetimeout=5000
EOF
  chmod 0640 /etc/asterisk/manager.d/ai-provisioner.conf
  if grep -qE '^[[:space:]]*enabled[[:space:]]*=' /etc/asterisk/manager.conf; then
    sed -Ei '0,/^[[:space:]]*enabled[[:space:]]*=.*/s//enabled = yes/' /etc/asterisk/manager.conf
  else
    sed -i '/^\[general\]/a enabled = yes' /etc/asterisk/manager.conf
  fi
  if grep -qE '^[[:space:]]*bindaddr[[:space:]]*=' /etc/asterisk/manager.conf; then
    sed -Ei '0,/^[[:space:]]*bindaddr[[:space:]]*=.*/s//bindaddr = 127.0.0.1/' /etc/asterisk/manager.conf
  else
    sed -i '/^\[general\]/a bindaddr = 127.0.0.1' /etc/asterisk/manager.conf
  fi
  if ! grep -Eq '^#include[[:space:]]+manager\.d/\*\.conf$' /etc/asterisk/manager.conf; then
    ensure_include /etc/asterisk/manager.conf '#include manager.d/ai-provisioner.conf'
  fi

  install -o root -g root -m 0755 "$voice_ast/upload-asterisk-recording.sh" \
    /usr/local/bin/upload-asterisk-recording.sh
  install -o root -g root -m 0755 "$voice_ast/retry-pending-asterisk-recordings.sh" \
    /usr/local/bin/retry-pending-asterisk-recordings.sh
  cat > /etc/asterisk/ai-agent-recording.conf <<EOF
DASHBOARD_BACKEND_URL=http://${SERVER_IP}:8000
DASHBOARD_INTERNAL_API_KEY=${INTERNAL_API_KEY}
DELETE_AFTER_UPLOAD=false
EOF
  chown root:"$ast_group" /etc/asterisk/ai-agent-recording.conf
  chmod 0640 /etc/asterisk/ai-agent-recording.conf
  cat > /etc/cron.d/mozaic-asterisk-recordings <<'EOF'
*/5 * * * * root /usr/local/bin/retry-pending-asterisk-recordings.sh >> /var/log/asterisk/recording-upload.log 2>&1
EOF
  chmod 0644 /etc/cron.d/mozaic-asterisk-recordings
  asterisk -rx 'core restart now' || systemctl restart asterisk
}

