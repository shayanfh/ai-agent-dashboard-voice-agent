CONFIG_ROOT="${CONFIG_ROOT:-/etc/mozaic-office}"
RUNTIME_DIR="${INSTALL_ROOT}/runtime"
STATE_FILE="${CONFIG_ROOT}/install.env"
LOG_FILE="/var/log/mozaic-office-install.log"

FRONTEND_REPO="https://github.com/rakibulinux/voice-agent-frontend.git"
